#!/usr/bin/env node
// Generates the API reference from the route table in hub/server.js:
//   docs/api/material-choco.postman_collection.json   (whole file)
//   docs/api/README.md                                (the table between the routes markers)
// Usage: node scripts/gen-api-docs.mjs [--check]
// --check writes nothing and exits 1 when either file no longer matches the route table.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const serverFile = path.join(root, 'hub', 'server.js');
const collectionFile = path.join(root, 'docs', 'api', 'material-choco.postman_collection.json');
const readmeFile = path.join(root, 'docs', 'api', 'README.md');
const START = '<!-- routes:start (generated by scripts/gen-api-docs.mjs) -->';
const END = '<!-- routes:end -->';

// ---- read the route table ------------------------------------------------------------------
// Every route is declared as route('METHOD', '/path', handler[, { open | agent | role }]).
// The options sit at the end of the call, so they are looked for between one declaration and the next.
const source = fs.readFileSync(serverFile, 'utf8');
const starts = [...source.matchAll(/\broute\('([A-Z]+)', '([^']+)'/g)];
if (!starts.length) { console.error('No routes found in hub/server.js'); process.exit(1); }
const routes = starts.map((m, i) => {
  const segment = source.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : source.indexOf('// ---- static files', m.index));
  const opts = [...segment.matchAll(/[})], \{ (open: true|agent: true|role: '(\w+)') \}\);/g)].pop();
  const method = m[1]; const route = m[2];
  let access = method === 'GET' ? 'viewer' : 'admin'; // the defaults applied in handle()
  if (opts) access = opts[1] === 'open: true' ? 'open' : opts[1] === 'agent: true' ? 'agent' : opts[2];
  return { method, path: route, access };
});

// ---- example request bodies ------------------------------------------------------------------------
const SPEC = { kind: 'choco', command: 'upgrade', args: ['git'], options: {}, global: { confirm: true } };
const WEBAUTHN_CREATE = { id: '<credential id>', response: { clientDataJSON: '<base64url>', attestationObject: '<base64url>', transports: ['internal'] }, name: 'My laptop' };
const WEBAUTHN_GET = { id: '<credential id>', response: { clientDataJSON: '<base64url>', authenticatorData: '<base64url>', signature: '<base64url>', userHandle: '<base64url>' } };
const BODIES = {
  'POST /api/setup': { name: 'admin', password: 'at least ten characters' },
  'POST /api/login': { name: 'admin', password: 'at least ten characters', totp: '123456' },
  'POST /api/login/passkey/begin': { name: 'admin' },
  'POST /api/login/passkey/finish': WEBAUTHN_GET,
  'PATCH /api/machines/:id': { name: 'PC-01', groups: ['lab'], readOnly: false, allowedCommands: ['list', 'outdated', 'upgrade'] },
  'POST /api/pairing': { readOnly: false, groups: ['lab'] },
  'POST /api/jobs': { machineIds: ['{{id}}'], spec: SPEC },
  'POST /api/schedules': { name: 'Nightly upgrade', time: '03:00', days: [], target: { all: true }, spec: { ...SPEC, args: ['all'] } },
  'PATCH /api/schedules/:id': { enabled: false },
  'POST /api/audit': { action: 'note', detail: 'text' },
  'POST /api/account/password': { current: 'current password', next: 'new password of ten or more' },
  'POST /api/account/totp': { action: 'begin' },
  'POST /api/account/passkeys/begin': { password: 'current password' },
  'POST /api/account/passkeys/finish': WEBAUTHN_CREATE,
  'POST /api/users': { name: 'olga', role: 'operator', password: 'initial password of ten or more' },
  'PATCH /api/users/:name': { role: 'viewer', disabled: false },
  'POST /api/webhooks': { name: 'Ops channel', url: 'https://example.com/hook', format: 'json', events: ['job.failed', 'machine.offline', 'login.lockout'], offlineMinutes: 10, enabled: true },
  'PATCH /api/webhooks/:id': { enabled: false },
  'POST /agent/enroll': { code: 'XXXX-XXXX', name: 'PC-01', info: { hostname: 'PC-01', os: 'Windows_NT 10.0', arch: 'x64', agentVersion: '0.1.0' } },
  'POST /agent/poll': { info: { hostname: 'PC-01', agentVersion: '0.1.0' } },
  'POST /agent/jobs/:id/output': { chunk: 'text printed by the command\n' },
  'POST /agent/jobs/:id/done': { code: 0, stderr: '', timedOut: false, cancelled: false, rejected: false },
};

// ---- Postman collection ----------------------------------------------------------------------------------
const params = new Set(); // :id, :name ... become {{id}}, {{name}} collection variables
function item(r) {
  const segments = r.path.split('/').filter(Boolean).map((s) => { if (!s.startsWith(':')) return s; params.add(s.slice(1)); return `{{${s.slice(1)}}}`; });
  const request = { method: r.method, header: r.access === 'agent' ? [{ key: 'Authorization', value: 'Bearer {{agentToken}}' }] : [], url: { raw: '{{baseUrl}}/' + segments.join('/'), host: ['{{baseUrl}}'], path: segments } };
  if (r.method === 'POST' || r.method === 'PATCH' || r.method === 'PUT') request.body = { mode: 'raw', raw: JSON.stringify(BODIES[`${r.method} ${r.path}`] || {}, null, 1), options: { raw: { language: 'json' } } };
  return { name: `${r.method} ${r.path}`, request };
}
const browser = routes.filter((r) => r.path.startsWith('/api/')).map(item);
const agent = routes.filter((r) => r.path.startsWith('/agent/')).map(item);
const collection = {
  info: { name: 'Material Choco hub', schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json', description: 'Generated from hub/server.js by scripts/gen-api-docs.mjs. Sign in with POST /api/login first; the session cookie is then sent automatically.' },
  variable: [{ key: 'baseUrl', value: 'http://localhost:8080' }, { key: 'agentToken', value: '' }, ...[...params].sort().map((key) => ({ key, value: '' }))],
  item: [{ name: 'Browser API', item: browser }, { name: 'Agent API', item: agent }],
};
const collectionText = JSON.stringify(collection, null, 1) + '\n';

// ---- README table -------------------------------------------------------------------------------------------
const WHO = { open: 'anyone (no session)', viewer: 'viewer, operator, admin', operator: 'operator, admin', admin: 'admin', agent: 'agent token' };
const table = ['| Method | Path | Who may call it |', '| --- | --- | --- |', ...routes.map((r) => `| ${r.method} | \`${r.path}\` | ${WHO[r.access]} |`)].join('\n');
const readme = fs.existsSync(readmeFile) ? fs.readFileSync(readmeFile, 'utf8') : '';
const a = readme.indexOf(START); const b = readme.indexOf(END);
if (a < 0 || b < a) { console.error(`docs/api/README.md needs the markers\n${START}\n${END}`); process.exit(1); }
const readmeText = readme.slice(0, a + START.length) + '\n' + table + '\n' + readme.slice(b);

// ---- write or check ---------------------------------------------------------------------------------------------
const outputs = [[collectionFile, collectionText], [readmeFile, readmeText]];
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text).map(([file]) => path.relative(root, file));
  if (stale.length) { console.error(`Out of date: ${stale.join(', ')}. Run: node scripts/gen-api-docs.mjs`); process.exit(1); }
  console.log(`API docs match the ${routes.length} routes in hub/server.js`);
} else {
  for (const [file, text] of outputs) fs.writeFileSync(file, text);
  console.log(`Wrote ${outputs.map(([file]) => path.relative(root, file)).join(' and ')} for ${routes.length} routes`);
}
