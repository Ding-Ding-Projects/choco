export function setVocabulary(entries) {
  seen.clear();
  vocab = entries && Object.keys(entries).length ? new Map(Object.entries(entries).map(([k, v]) => [k.toLowerCase(), v])) : null;
  vocabRe = vocab ? new RegExp('(?<![\\p{L}\\p{N}])(' + [...vocab.keys()].sort((a, b) => b.length - a.length).map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|') + ')(?![\\p{L}\\p{N}])', 'giu') : null;
}
export const hasVocabulary = () => !!vocab;
const swap = (s) => s.replace(vocabRe, (m) => vocab.get(m.toLowerCase()) ?? m);
// Applies the personal wording file to prose. Placeholders such as {n} and spans marked with lit() are left alone.
const personal = (s) => (vocabRe && !settings.school ? String(s).split(/(\{\w+\}|\uE000[^\uE001]*\uE001)/).map((part, i) => (i % 2 ? part : swap(part))).join('') : s);
// lit(x) marks exact technical text (a command, a package id, a path, a machine name) inside a
// sentence that is passed to say(), so that the wording file never rewrites it. The marks are
// two private-use characters that say() and the element builder remove before anything is shown.
export const lit = (x) => '\uE000' + String(x ?? '') + '\uE001';
export const unmark = (s) => (typeof s === 'string' && (s.includes('\uE000') || s.includes('\uE001')) ? s.replace(/[\uE000\uE001]/g, '') : s);
// Strings that already went through the wording file, so that say() does not process them twice.
const seen = new Set(); const remember = (s) => { if (seen.size > 4000) seen.clear(); seen.add(s); return s; };
// The choke point for prose that was written in place: notifications, error panels, takeovers,
// empty states, confirmations and narration all pass their text through here.
export function say(text) {
  if (typeof text !== 'string' || !text) return text; if (seen.has(text)) return text;
  if (!vocabRe || settings.school) return unmark(text);
  const guarded = text.replace(/(?<!\uE000)\bhttps?:\/\/\S+|(?<![\w\uE000])--[\w-]+(?:=\S+)?/g, (m) => lit(m));
  return remember(unmark(personal(guarded)));
}
